export const FRANCE_DEPARTMENTS: Territory[] = DEPT_SEEDS.map(([code, name, groupId, aliases = []], idx) => {
  const enName = code === '973' ? 'French Guiana' : code === '974' ? 'Réunion' : name;
  const enAliases = code === '973' ? ['Guyane'] : code === '974' ? ['La Reunion'] : aliases;
  const baseColor = REGION_COLOR_MAP[groupId] ?? 0;

  return {
    id: `FR${code}`,
    code,
    names: { fr: name, en: enName },
    aliases: { fr: aliases, en: enAliases },
    groupId,
    colorIndex: (baseColor + (idx % 3)) % 5,
  };
});
