export const WORLD_COUNTRIES: Territory[] = COUNTRY_SEEDS.map(
  ([id, groupId, frName, enName, frAliases = [], enAliases = []], idx) => {
    const base = CONTINENT_COLOR_BASE[groupId] ?? 0;
    return {
      id,
      names: { fr: frName, en: enName },
      aliases: { fr: frAliases, en: enAliases },
      groupId,
      colorIndex: (base + (idx % 4)) % 5,
    };
  }
);
